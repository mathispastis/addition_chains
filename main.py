def run_worst_greedy(input_data):
    """
    Runs the worst-case branching greedy search.
    Accepts either a raw string OR an existing grammar dictionary.
    """
    # 1. Check if the input is ALREADY a pre-compressed grammar dictionary
    if isinstance(input_data, dict):
        initial_grammar = input_data
        # If A0 and A1 exist, length is 2, so the next rule should be A2!
        starting_rule_counter = len(initial_grammar)

        # 2. Otherwise, treat it as a raw string/list and start fresh
    else:
        initial_grammar = {'A0': list(input_data)}
        starting_rule_counter = 1

    # Run the branching algorithm
    all_possible_grammars = greedy_worst_branching(initial_grammar, rule_counter=starting_rule_counter)

    # Return the worst (longest) grammar5
    worst_grammar = max(all_possible_grammars, key=addition_chain_length)

    return worst_grammar


