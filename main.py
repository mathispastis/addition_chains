def get_first_iteration_state(s):
    """
    Finds the substring with the maximum savings, replaces it with 'A',
    and returns the formatted string: {new_string|replaced_string}.
    """
    n = len(s)
    max_savings = -1
    best_sub = ""

    # We only need to check up to half the string's length
    for L in range(2, n // 2 + 1):
        seen = set()
        candidates = set()

        # Fast Hash-Set Sieve: Instantly find repeating substrings
        for i in range(n - L + 1):
            sub = s[i:i + L]
            if sub in seen:
                candidates.add(sub)
            else:
                seen.add(sub)

        # EARLY EXIT: If no string of length L repeats, longer ones mathematically cannot!
        if not candidates:
            break

        # Sort candidates to ensure deterministic tie-breaking (e.g., 'ab' vs 'ba')
        for sub in sorted(candidates):
            # Use C-engine for lightning-fast non-overlapping counting
            k = s.count(sub)
            if k < 2:
                continue

            savings = (L - 1) * k - L

            # Track the absolute maximum savings
            if savings > max_savings:
                max_savings = savings
                best_sub = sub

    # If no compression is possible at all
    if best_sub == "":
        return f"{{{s}|}}"

    # Apply the replacement and format the return string
    new_string = s.replace(best_sub, "C")
    return f"{{{new_string}|{best_sub}}}"


