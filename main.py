def fibonacci_word(i):
    if i < 1:
        raise ValueError("Index i must be 1 or greater.")
    if i == 1:
        return "b"
    if i == 2:
        return "a"

    f_minus_2 = "b"  # F_1
    f_minus_1 = "a"  # F_2
    current_f = ""

    for _ in range(3, i + 1):
        current_f = f_minus_1 + f_minus_2
        f_minus_2 = f_minus_1
        f_minus_1 = current_f

    return current_f


from collections import defaultdict


def get_max_saving_sequences(grammar):
    """
    An ultra-optimized C-engine implementation to find the maximum savings.
    Uses Unicode mapping to calculate non-overlapping counts instantly.
    """
    # 1. Map tokens to Unicode characters to unlock C-speed string methods
    token_to_char = {}
    char_to_token = {}
    next_char_id = 1

    string_rules = []

    # Convert every rule list into a native Python string
    for rule in grammar.values():
        char_list = []
        for token in rule:
            if token not in token_to_char:
                # Map the token to a single, unique Unicode character
                char = chr(next_char_id)
                token_to_char[token] = char
                char_to_token[char] = token
                next_char_id += 1
            char_list.append(token_to_char[token])

        string_rules.append("".join(char_list))

    best_sequences_chars = []
    max_savings = -1


    max_len = max((len(r) for r in string_rules), default=0)

    # 2. Search length by length, starting at pairs (L=2)
    for L in range(2, max_len + 1):

        counts = defaultdict(int)
        for rule_str in string_rules:
            for i in range(len(rule_str) - L + 1):
                counts[rule_str[i: i + L]] += 1

        candidates = [sub for sub, c in counts.items() if c >= 2]


        if not candidates:
            break


        for sub_str in candidates:
            k = sum(rule_str.count(sub_str) for rule_str in string_rules)

            if k < 2:
                continue

            current_savings = (L - 1) * k - L

            if current_savings > max_savings:
                max_savings = current_savings
                best_sequences_chars = [sub_str]
            elif current_savings == max_savings and current_savings > -1:
                best_sequences_chars.append(sub_str)
    best_sequences = [
        tuple(char_to_token[char] for char in seq)
        for seq in best_sequences_chars
    ]

    return best_sequences, max_savings


def analyze_fibonacci_first_step(fib_index):
    fib_string = fibonacci_word(fib_index)
    initial_grammar = {'A0': list(fib_string)}
    best_sequences, max_savings = get_max_saving_sequences(initial_grammar)
    best_strings = ["".join(seq) for seq in best_sequences]
    return best_strings, max_savings


