def precompress_for_standard_greedy(n):
    """
    Pre-compresses F_{6n-3} using P_{3n} and perfectly formats it
    into the dictionary-of-lists format required by your standard
    greedy_worst_branching algorithm.
    """
    idx_target = 6 * n - 3
    idx_p = 3 * n

    F_target = fibonacci_word(idx_target)
    F_p = fibonacci_word(idx_p)
    P_3n = F_p[:-2]

    # We split the large string exactly where P_3n appears
    parts = F_target.split(P_3n)

    a0_tokens = []

    # Rebuild the list, inserting 'A1' as a single protected token
    for i, part in enumerate(parts):
        # Add the leftover 'a' and 'b' characters individually
        a0_tokens.extend(list(part))

        # Inject the 'A1' rule token between the parts
        if i < len(parts) - 1:
            a0_tokens.append('A1')

    # Build the exact dictionary structure your original algorithm expects
    grammar = {
        'A0': a0_tokens,
        'A1': list(P_3n)
    }

    return grammar


def precompress_for_standard_greedy2(n):
    """
    Pre-compresses F_{6n-3} by mathematically executing Step 1 and Step 2.
    Step 1: Replace P_{3n} with 'A1'
    Step 2: Accounts for the Fibonacci parity flip!
            If n is odd, uses 'ab'. If n is even, uses 'ba'.
    """
    idx_target = 6 * n - 3
    idx_p = 3 * n
    idx_f = 3 * n - 3

    # 1. Generate all required Fibonacci strings
    F_target = fibonacci_word(idx_target)
    F_p = fibonacci_word(idx_p)
    P_3n = F_p[:-2]

    F_3n_minus_3 = fibonacci_word(idx_f)

    # ==========================================
    # STEP 1: Replace P_{3n} with 'A1'
    # ==========================================
    parts = F_target.split(P_3n)
    a0_step1 = []

    for i, part in enumerate(parts):
        a0_step1.extend(list(part))
        if i < len(parts) - 1:
            a0_step1.append('A1')

    # ==========================================
    # STEP 2: Replace target sequence with 'A2'
    # ==========================================
    # Handle the Parity Flip based on n
    if n % 2 != 0:  # If n is odd
        c1, c2 = 'a', 'b'
    else:  # If n is even
        c1, c2 = 'b', 'a'

    target_seq_2 = ['A1', c1, c2, 'A1', c1, c2] + list(F_3n_minus_3)
    target_len = len(target_seq_2)

    a0_step2 = []
    i = 0
    length_a0 = len(a0_step1)
    occurrences_step2 = 0

    # Fast list replacement loop
    while i < length_a0:
        # Check if the current slice matches our target sequence
        if i <= length_a0 - target_len and a0_step1[i:i + target_len] == target_seq_2:
            a0_step2.append('A2')
            occurrences_step2 += 1
            i += target_len  # Jump past the replaced sequence
        else:
            a0_step2.append(a0_step1[i])
            i += 1

    # ==========================================
    # Finalize Grammar
    # ==========================================
    grammar = {
        'A0': a0_step2,
        'A1': list(P_3n),
        'A2': target_seq_2
    }

    # Just for clean printing
    connector = f"{c1}{c2}"

    print(f"--- 2-Step Pre-Compression Complete for n={n} (F_{idx_target}) ---")
    print(f"Rule A1 created: P_{idx_p} (Length {len(P_3n)})")
    print(
        f"Rule A2 created: A1{connector}A1{connector}F_{idx_f} (Length {target_len}), Found {occurrences_step2} times")
    print(f"Current A0 length: {len(a0_step2)}\n")

    return grammar




