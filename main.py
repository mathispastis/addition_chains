def get_fibonacci_length(i):
    """Calculates the i-th Fibonacci number (the length of F_i)."""
    if i == 1 or i == 2: return 1
    a, b = 1, 1
    for _ in range(3, i + 1):
        a, b = b, a + b
    return b







